def nest(lang_index):
    out = {}
    for key, pair in S.items():
        node = out.setdefault("AF", {})
        parts = key.split(".")
        for p in parts[:-1]:
            node = node.setdefault(p, {})
        node[parts[-1]] = pair[lang_index]
    return out


